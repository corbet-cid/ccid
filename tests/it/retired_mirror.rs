//! The CI files of the mirror forges are retired at every schema (operating model R6, R7, R46): ccid renders none of
//! them, `render` removes the ones an earlier release rendered, and `render --check` names them as drift.

use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
};

const MARKER: &str = "# Generated by ccid render v1; edit .ci/ccid.toml instead.\n";
const BINARY: &str = env!("CARGO_BIN_EXE_ccid");

/// Every path an earlier release rendered for a mirror forge.
const RETIRED: [&str; 5] = [
    ".github/workflows/jsr-publish.yml",
    ".github/workflows/pr-check.yml",
    ".github/workflows/release-mirror.yml",
    ".gitlab-ci.yml",
    "bitbucket-pipelines.yml",
];

fn git(root: &Path, args: &[&str]) {
    let output = Command::new("git")
        .args([
            "-c",
            "core.hooksPath=/dev/null",
            "-c",
            "commit.gpgsign=false",
            "-c",
            "user.name=retired-test",
            "-c",
            "user.email=retired-test@example.invalid",
            "-c",
            "init.defaultBranch=main",
        ])
        .args(args)
        .current_dir(root)
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "git {args:?}: {}",
        String::from_utf8_lossy(&output.stderr)
    );
}

fn write(root: &Path, relative: &str, content: &str) {
    let path = root.join(relative);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, content).unwrap();
}

fn commit(root: &Path) {
    git(root, &["add", "-A"]);
    git(root, &["commit", "-q", "--allow-empty", "-m", "fixture"]);
}

fn manifest(schema: u8) -> String {
    format!(
        "schema = 1\nproject = \"retired\"\nrepository = \"https://forge.example/org/retired\"\n\n\
         [render]\nrender_schema = {schema}\n\n\
         [checks.test]\nkind = \"commands\"\ncommands = [[\"true\"]]\n\n\
         [jobs.verify]\nscheduler = \"forgejo\"\nruns_on = \"linux\"\nchecks = [\"test\"]\nworkflow = \"ci\"\ncommand = [\"ccid:run-declared-checks\"]\n"
    )
}

/// A committed repository at `schema` whose origin is a GitHub copy, with every retired file an earlier release
/// rendered (each carries the render marker).
fn repository(schema: u8, extra: &[(&str, &str)]) -> tempfile::TempDir {
    let root = tempfile::tempdir().unwrap();
    git(root.path(), &["init", "-q"]);
    git(
        root.path(),
        &[
            "remote",
            "add",
            "origin",
            "https://github.example/org/retired.git",
        ],
    );
    write(root.path(), ".ci/ccid.toml", &manifest(schema));
    ccid::render::render(root.path(), Path::new(".ci/ccid.toml"), false).unwrap();
    for relative in RETIRED {
        write(
            root.path(),
            relative,
            &format!("{MARKER}# a release mirror or a check of an earlier ccid\n"),
        );
    }
    for (relative, content) in extra {
        write(root.path(), relative, content);
    }
    commit(root.path());
    root
}

fn render(root: &Path, check: bool) -> ccid::Result<ccid::render::Report> {
    ccid::render::render(root, Path::new(".ci/ccid.toml"), check)
}

fn retired_paths() -> Vec<PathBuf> {
    RETIRED.iter().map(PathBuf::from).collect()
}

#[test]
fn no_schema_renders_a_file_for_a_mirror_forge() {
    for schema in [2, 3] {
        let root = tempfile::tempdir().unwrap();
        git(root.path(), &["init", "-q"]);
        git(
            root.path(),
            &[
                "remote",
                "add",
                "origin",
                "https://github.example/org/retired.git",
            ],
        );
        write(root.path(), ".ci/ccid.toml", &manifest(schema));
        let report = render(root.path(), false).unwrap();
        for relative in RETIRED {
            assert!(
                !report.files.contains(&PathBuf::from(relative)),
                "schema {schema} renders {relative}"
            );
            assert!(!root.path().join(relative).exists(), "{relative}");
        }
    }
}

/// A render removes every retired file and leaves a repository whose check is clean.
fn render_removes_them(root: &Path, schema: u8) {
    let mut removed = render(root, false).unwrap().removed;
    removed.sort();
    assert_eq!(removed, retired_paths(), "schema {schema}");
    for relative in RETIRED {
        assert!(!root.join(relative).exists(), "{relative}");
    }
    commit(root);
    let report = render(root, true).unwrap();
    assert!(report.removed.is_empty() && report.transitional.is_empty());
}

#[test]
fn schemas_one_and_two_accept_the_presence_of_the_retired_files_and_a_render_removes_them() {
    let root = repository(2, &[]);
    // A declared transition: a channel bump re-stales no repository that still carries the files.
    let report = render(root.path(), true).unwrap();
    assert_eq!(report.transitional, retired_paths());
    assert!(report.removed.is_empty());
    for relative in RETIRED {
        assert!(
            root.path().join(relative).exists(),
            "a check removes nothing: {relative}"
        );
    }
    // The tolerance covers only the retired files: any other drift is still red, and the retired files are not
    // named in its message.
    write(
        root.path(),
        ".forgejo/workflows/ci.yml",
        "# Generated by ccid render v1; edit .ci/ccid.toml instead.\nstale: true\n",
    );
    let message = render(root.path(), true).unwrap_err().to_string();
    assert!(message.contains(".forgejo/workflows/ci.yml"), "{message}");
    assert!(!message.contains("retired"), "{message}");
    git(
        root.path(),
        &["checkout", "-q", "--", ".forgejo/workflows/ci.yml"],
    );
    render_removes_them(root.path(), 2);
}

#[test]
fn schema_three_names_the_retired_files_as_drift_and_a_render_removes_them() {
    let root = repository(3, &[]);
    let message = render(root.path(), true).unwrap_err().to_string();
    assert!(
        message.contains("Generated job adapters have drifted"),
        "{message}"
    );
    for relative in RETIRED {
        assert!(
            message.contains(&format!("{relative} (retired, render removes it: nothing:")),
            "{relative}: {message}"
        );
        // A check removes nothing.
        assert!(root.path().join(relative).exists(), "{relative}");
    }
    render_removes_them(root.path(), 3);
}

#[test]
fn a_hand_written_file_at_a_retired_path_is_not_ours_to_remove() {
    let hand = "include: upstream.yml\n";
    // Schemas 1 and 2 never touch it.
    let old = tempfile::tempdir().unwrap();
    git(old.path(), &["init", "-q"]);
    write(old.path(), ".ci/ccid.toml", &manifest(2));
    render(old.path(), false).unwrap();
    write(old.path(), ".gitlab-ci.yml", hand);
    write(
        old.path(),
        ".github/workflows/release-mirror.yml",
        "on: push\n",
    );
    commit(old.path());
    render(old.path(), true).unwrap();
    render(old.path(), false).unwrap();
    assert_eq!(
        fs::read_to_string(old.path().join(".gitlab-ci.yml")).unwrap(),
        hand
    );
    assert!(old
        .path()
        .join(".github/workflows/release-mirror.yml")
        .exists());
    // Schema 3 accounts for it as an unknown file: the person decides.
    let surface = tempfile::tempdir().unwrap();
    git(surface.path(), &["init", "-q"]);
    write(surface.path(), ".ci/ccid.toml", &manifest(3));
    write(
        surface.path(),
        ".github/workflows/release-mirror.yml",
        "on: push\n",
    );
    commit(surface.path());
    let message = render(surface.path(), false).unwrap_err().to_string();
    assert!(
        message.contains(".github/workflows/release-mirror.yml (unknown"),
        "{message}"
    );
    assert!(surface
        .path()
        .join(".github/workflows/release-mirror.yml")
        .exists());
}

#[test]
fn schema_three_classes_the_retired_files_as_legacy_and_delete() {
    let root = repository(3, &[]);
    let output = Command::new(BINARY)
        .args(["surface", "report", "--repo"])
        .arg(root.path())
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    let report: serde_json::Value = serde_json::from_slice(&output.stdout).unwrap();
    for relative in RETIRED {
        let item = report["files"]
            .as_array()
            .unwrap()
            .iter()
            .find(|item| item["path"] == relative)
            .unwrap_or_else(|| panic!("{relative} is not in the report"));
        assert_eq!(item["class"], "legacy", "{relative}");
        assert_eq!(item["action"], "delete", "{relative}");
        let family = if relative == "bitbucket-pipelines.yml" {
            "bitbucket"
        } else {
            "mirror-ci"
        };
        assert_eq!(item["family"], family, "{relative}");
    }
}

#[test]
fn schema_three_removes_only_what_git_can_restore() {
    let root = repository(3, &[]);
    // A retired file that differs from its commit is refused, and nothing is written.
    write(
        root.path(),
        ".gitlab-ci.yml",
        &format!("{MARKER}# changed after the commit\n"),
    );
    let message = render(root.path(), false).unwrap_err().to_string();
    assert!(
        message.contains(".gitlab-ci.yml (legacy mirror-ci: not committed as it is"),
        "{message}"
    );
    for relative in RETIRED {
        assert!(root.path().join(relative).exists(), "{relative}");
    }
}

#[cfg(unix)]
#[test]
fn a_symlink_at_a_retired_path_is_never_followed_or_removed() {
    let root = tempfile::tempdir().unwrap();
    git(root.path(), &["init", "-q"]);
    write(root.path(), ".ci/ccid.toml", &manifest(2));
    render(root.path(), false).unwrap();
    write(
        root.path(),
        "elsewhere.yml",
        &format!("{MARKER}# not ours to delete\n"),
    );
    fs::create_dir_all(root.path().join(".github/workflows")).unwrap();
    std::os::unix::fs::symlink(
        "../../elsewhere.yml",
        root.path().join(".github/workflows/release-mirror.yml"),
    )
    .unwrap();
    commit(root.path());
    render(root.path(), true).unwrap();
    let report = render(root.path(), false).unwrap();
    assert!(report.removed.is_empty());
    assert!(root.path().join("elsewhere.yml").exists());
    assert!(
        fs::symlink_metadata(root.path().join(".github/workflows/release-mirror.yml"))
            .unwrap()
            .file_type()
            .is_symlink()
    );
}
