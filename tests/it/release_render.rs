//! What `[release]` renders at `render_schema = 3`: the release workflow with its `needs` order and its
//! conditions, the JSR publisher, the planned jobs in the inventory, and the refusals around them.

use std::{fs, path::Path, process::Command};

const HEAD: &str = "schema = 1\nproject = \"demo\"\n\n[render]\nrender_schema = 3\n\n\
    [checks.build]\nkind = \"commands\"\ncommands = [[\"true\"]]\n\n\
    [checks.win]\nkind = \"commands\"\ncommands = [[\"true\"]]\n\n\
    [checks.mac]\nkind = \"commands\"\ncommands = [[\"true\"]]\n\n\
    [checks.seal]\nkind = \"commands\"\ncommands = [[\"true\"]]\n\n\
    [checks.test]\nkind = \"commands\"\ncommands = [[\"true\"]]\n\n\
    [jobs.verify]\nscheduler = \"forgejo\"\nchecks = [\"test\"]\nworkflow = \"ci\"\ncommand = [\"ccid:run-declared-checks\"]\n\n";

const BINARY: &str = "[release]\nkind = \"binary\"\nversion = \"Cargo.toml\"\n\
    platforms = [\"linux-x86_64\", \"windows-x86_64\", \"macos-x86_64\", \"macos-arm64\"]\n\
    build = [\"build\"]\nlegs = { windows = \"win\", macos = \"mac\" }\nseal = [\"seal\"]\nmanifests = [\"manifest.json\"]\n";

const LIBRARY: &str =
    "[release]\nkind = \"library\"\nversion = \"Cargo.toml\"\nbuild = [\"build\"]\nregistries = [\"crates\", \"jsr\"]\n";

fn git(root: &Path, args: &[&str]) {
    let output = Command::new("git")
        .args([
            "-c",
            "commit.gpgsign=false",
            "-c",
            "user.name=t",
            "-c",
            "user.email=t@example.invalid",
            "-c",
            "init.defaultBranch=main",
        ])
        .args(args)
        .current_dir(root)
        .output()
        .unwrap();
    assert!(output.status.success(), "git {args:?}");
}

fn repository(manifest: &str, files: &[(&str, &str)]) -> tempfile::TempDir {
    let root = tempfile::tempdir().unwrap();
    git(root.path(), &["init", "-q"]);
    write(root.path(), ".ci/ccid.toml", manifest);
    write(
        root.path(),
        "Cargo.toml",
        "[package]\nname = \"demo\"\nversion = \"0.1.0\"\n",
    );
    for (relative, content) in files {
        write(root.path(), relative, content);
    }
    git(root.path(), &["add", "-A"]);
    git(root.path(), &["commit", "-q", "-m", "fixture"]);
    root
}

fn write(root: &Path, relative: &str, content: &str) {
    let path = root.join(relative);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, content).unwrap();
}

fn render(root: &Path, check: bool) -> ccid::Result<ccid::render::Report> {
    ccid::render::render(root, Path::new(".ci/ccid.toml"), check)
}

fn read(root: &Path, relative: &str) -> String {
    fs::read_to_string(root.join(relative)).unwrap()
}

#[test]
fn a_binary_release_renders_the_leg_chain_and_promotion_after_every_leg_that_ran() {
    let root = repository(&format!("{HEAD}{BINARY}"), &[]);
    let report = render(root.path(), false).unwrap();
    assert!(report
        .files
        .contains(&".forgejo/workflows/release.yml".into()));
    let workflow = read(root.path(), ".forgejo/workflows/release.yml");
    for expected in [
        "# Generated by ccid render v1; edit .ci/ccid.toml instead.\n",
        "name: release\non:\n  workflow_dispatch:\n",
        "cancel-in-progress: false",
        "  release:\n    runs-on: linux\n    outputs:\n      legs: ${{ steps.run.outputs.legs }}\n      released: ${{ steps.run.outputs.released }}\n",
        "  release-windows:\n    needs: [release]\n",
        "contains(needs.release.outputs.legs, 'windows')",
        "    runs-on: windows\n",
        "  release-macos:\n    needs: [release, release-windows]\n",
        "contains(needs.release.outputs.legs, 'macos') && (needs.release-windows.result == 'success' || needs.release-windows.result == 'skipped')",
        "    runs-on: macos\n",
        "  release-promote:\n    needs: [release, release-windows, release-macos]\n",
        "needs.release.outputs.released == 'true' && (needs.release-windows.result == 'success' || needs.release-windows.result == 'skipped') && (needs.release-macos.result == 'success' || needs.release-macos.result == 'skipped')",
        "exec \"$tool\" job-run --job 'release-macos'",
        "class='macos'",
        "        id: run\n",
    ] {
        assert!(workflow.contains(expected), "missing {expected:?} in\n{workflow}");
    }
    // The planned jobs are in the inventory with their sentinel commands and labels.
    let inventory: serde_json::Value =
        serde_json::from_str(&read(root.path(), ".ci/jobs.json")).unwrap();
    let jobs = &inventory["jobs"];
    assert_eq!(jobs["release"]["command"][0], "ccid:release-build");
    assert_eq!(jobs["release-windows"]["runs_on"], "windows");
    assert_eq!(jobs["release-macos"]["command"][0], "ccid:release-leg");
    assert_eq!(jobs["release-promote"]["checks"][0], "seal");
    // The render is stable and a check passes; no JSR file without the registry.
    render(root.path(), true).unwrap();
    assert!(!root
        .path()
        .join(".github/workflows/jsr-publish.yml")
        .exists());
}

#[test]
fn a_library_release_has_no_leg_and_a_jsr_registry_renders_the_publisher() {
    let root = repository(&format!("{HEAD}{LIBRARY}"), &[]);
    render(root.path(), false).unwrap();
    let workflow = read(root.path(), ".forgejo/workflows/release.yml");
    assert!(!workflow.contains("release-windows") && !workflow.contains("release-macos"));
    assert!(
        workflow.contains("  release-promote:\n    needs: [release]\n"),
        "{workflow}"
    );
    let jsr = read(root.path(), ".github/workflows/jsr-publish.yml");
    for expected in [
        "# Generated by ccid render v1; edit .ci/ccid.toml instead.\n",
        "tags: ['v*']",
        "id-token: write",
        "contents: read",
        "deno publish",
        "github.event.repository.private == false",
    ] {
        assert!(jsr.contains(expected), "missing {expected:?} in\n{jsr}");
    }
    // It only publishes: no build matrix, no tests, no secret of ours.
    assert!(
        !jsr.contains("secrets.") && !jsr.contains("matrix") && !jsr.contains("cargo "),
        "{jsr}"
    );
    render(root.path(), true).unwrap();
    // Dropping the registry removes the file the renderer owns.
    write(
        root.path(),
        ".ci/ccid.toml",
        &format!("{HEAD}{}", LIBRARY.replace(", \"jsr\"", "")),
    );
    git(root.path(), &["add", "-A"]);
    git(root.path(), &["commit", "-q", "-m", "no jsr"]);
    let report = render(root.path(), false).unwrap();
    assert_eq!(
        report.removed,
        vec![Path::new(".github/workflows/jsr-publish.yml")]
    );
}

#[test]
fn the_release_table_is_refused_where_it_cannot_work() {
    // Not at render_schema 2.
    let old = format!("{HEAD}{BINARY}").replace("render_schema = 3", "render_schema = 2");
    let error = render(repository(&old, &[]).path(), false)
        .unwrap_err()
        .to_string();
    assert!(error.contains("render_schema = 3"), "{error}");
    // A declared job cannot take a name or a workflow the release owns.
    let job = format!("{HEAD}{BINARY}\n[jobs.release]\nscheduler = \"forgejo\"\nchecks = [\"build\"]\nworkflow = \"x\"\ncommand = [\"ccid:run-declared-checks\"]\nevents = [\"manual\"]\n");
    let error = render(repository(&job, &[]).path(), false)
        .unwrap_err()
        .to_string();
    assert!(error.contains("plans the jobs release"), "{error}");
    let workflow = format!("{HEAD}{BINARY}\n[jobs.deep]\nscheduler = \"forgejo\"\nchecks = [\"build\"]\nworkflow = \"release\"\ncommand = [\"ccid:run-declared-checks\"]\nevents = [\"manual\"]\n");
    let error = render(repository(&workflow, &[]).path(), false)
        .unwrap_err()
        .to_string();
    assert!(error.contains("owns the workflow release"), "{error}");
    // Platforms without their leg, a leg without platforms, a library with platforms, unknown checks.
    for (change, expected) in [
        (
            BINARY.replace("legs = { windows = \"win\", macos = \"mac\" }\n", ""),
            "legs.windows",
        ),
        (
            BINARY.replace(
                "legs = { windows = \"win\", macos = \"mac\" }",
                "legs = { windows = \"win\" }",
            ),
            "legs.macos",
        ),
        (BINARY.replace("\"windows-x86_64\", ", ""), "legs.windows"),
        (BINARY.replace("\"linux-x86_64\", ", ""), "linux-x86_64"),
        (
            BINARY.replace("build = [\"build\"]", "build = [\"nope\"]"),
            "build",
        ),
        (
            BINARY.replace("manifests = [\"manifest.json\"]", ""),
            "go together",
        ),
        (
            LIBRARY.replace(
                "kind = \"library\"",
                "kind = \"library\"\nplatforms = [\"linux-x86_64\"]",
            ),
            "no platforms",
        ),
        (BINARY.replace("Cargo.toml", "VERSION"), "version file"),
    ] {
        let manifest = format!("{HEAD}{change}");
        let error = render(repository(&manifest, &[]).path(), false)
            .unwrap_err()
            .to_string();
        assert!(error.contains(expected), "{expected}: {error}");
    }
}

#[test]
fn a_hand_written_release_workflow_is_replaced_once_the_table_declares_the_release_and_refused_before(
) {
    let hand = [
        (
            ".forgejo/workflows/release.yml",
            "name: release\non: workflow_dispatch\n",
        ),
        (
            ".forgejo/workflows/release-macos.yml",
            "name: release-macos\non: workflow_dispatch\n",
        ),
    ];
    // Without [release] the files wait for their replacement: the repository stays as it is, and render refuses.
    let waiting = repository(HEAD.trim_end(), &hand);
    let error = render(waiting.path(), false).unwrap_err().to_string();
    assert!(
        error.contains("forgejo-release") || error.contains("release.yml"),
        "{error}"
    );
    // With [release] the rendered workflow replaces release.yml and the macOS file goes.
    let live = repository(&format!("{HEAD}{BINARY}"), &hand);
    let report = render(live.path(), false).unwrap();
    assert!(read(live.path(), ".forgejo/workflows/release.yml")
        .starts_with("# Generated by ccid render v1"));
    assert_eq!(
        report.removed,
        vec![Path::new(".forgejo/workflows/release-macos.yml")]
    );
}
