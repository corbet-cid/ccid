//! The mirror platforms' pull-request and merge-request checks (`render_schema = 3`): what render writes
//! for GitHub and GitLab, which verdict jobs it leaves on the forge and why, and the check script itself,
//! run for real against a fake forge (`tests/it/fixtures/mirror-check-fake-curl`) and a fake `nix-store`.
//! The tests need `sh`, `git`, `grep`, `tr`, `cut` and `sha256sum`.

use serde_json::json;
use sha2::{Digest, Sha256};
use std::{
    fs,
    os::unix::fs::PermissionsExt,
    path::{Path, PathBuf},
    process::{Command, Stdio},
};

const MANIFEST: &str = "schema = 1\nproject = \"demo\"\nrepository = \"https://git.example/team/demo\"\n\n\
    [render]\nrender_schema = 3\n\n\
    [checks.test]\nkind = \"commands\"\ncommands = [[\"true\"]]\n\n\
    [jobs.verify]\nscheduler = \"forgejo\"\nchecks = [\"test\"]\nworkflow = \"ci\"\ncommand = [\"ccid:run-declared-checks\"]\n";

fn git(root: &Path, args: &[&str]) {
    let output = Command::new("git")
        .args([
            "-c",
            "commit.gpgsign=false",
            "-c",
            "user.name=mirror-check-test",
            "-c",
            "user.email=mirror-check-test@example.invalid",
            "-c",
            "init.defaultBranch=main",
        ])
        .args(args)
        .current_dir(root)
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "git {args:?}: {}",
        String::from_utf8_lossy(&output.stderr)
    );
}

/// A committed repository with the manifest and `files`.
fn repository(manifest: &str, files: &[(&str, &str)]) -> tempfile::TempDir {
    let root = tempfile::tempdir().unwrap();
    git(root.path(), &["init", "-q"]);
    write(root.path(), ".ci/ccid.toml", manifest);
    for (relative, content) in files {
        write(root.path(), relative, content);
    }
    commit(root.path());
    root
}

fn write(root: &Path, relative: &str, content: &str) {
    let path = root.join(relative);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, content).unwrap();
}

fn commit(root: &Path) {
    git(root, &["add", "-A"]);
    git(root, &["commit", "-q", "--allow-empty", "-m", "fixture"]);
}

fn render(root: &Path, check: bool) -> ccid::Result<ccid::render::Report> {
    ccid::render::render(root, Path::new(".ci/ccid.toml"), check)
}

fn read(root: &Path, relative: &str) -> String {
    fs::read_to_string(root.join(relative)).unwrap()
}

fn error(root: &Path) -> String {
    render(root, false).unwrap_err().to_string()
}

/// The check script of `.github/workflows/pr-check.yml`: the here-document its step pipes into the container.
fn github_script(workflow: &str) -> String {
    let lines: Vec<&str> = workflow.lines().collect();
    let start = lines
        .iter()
        .position(|line| line.contains("<<'CCID_MIRROR_CHECK'"))
        .expect("the step pipes the script into the container")
        + 1;
    let end = start
        + lines[start..]
            .iter()
            .position(|line| line.trim() == "CCID_MIRROR_CHECK")
            .expect("the here-document ends");
    dedent(&lines[start..end])
}

/// The check script of the `mr-check` job of `.gitlab-ci.yml`.
fn gitlab_script(pipeline: &str) -> String {
    let lines: Vec<&str> = pipeline.lines().collect();
    let job = lines
        .iter()
        .position(|line| *line == "mr-check:")
        .expect("a merge-request check");
    let start = job
        + 1
        + lines[job + 1..]
            .iter()
            .position(|line| line.trim() == "- |")
            .unwrap()
        + 1;
    let indent = lines[start].len() - lines[start].trim_start().len();
    let end = start
        + lines[start..]
            .iter()
            .position(|line| {
                !line.trim().is_empty() && line.len() - line.trim_start().len() < indent
            })
            .unwrap_or(lines.len() - start);
    dedent(&lines[start..end])
}

fn dedent(lines: &[&str]) -> String {
    let indent = lines
        .iter()
        .find(|line| !line.trim().is_empty())
        .map(|line| line.len() - line.trim_start().len())
        .unwrap();
    let text = lines
        .iter()
        .map(|line| line.get(indent..).unwrap_or(""))
        .collect::<Vec<_>>()
        .join("\n");
    format!("{}\n", text.trim_end_matches('\n'))
}

