// ---- the check script, run for real -------------------------------------------------------------

struct Stage {
    dir: tempfile::TempDir,
    script: String,
    tool_source: String,
}

struct Outcome {
    code: i32,
    stderr: String,
}

fn sha(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

const NIX_LOADER: &str =
    "/nix/store/aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa-glibc-2.42-84/lib/ld-linux-x86-64.so.2";

impl Stage {
    /// A fake forge and the script `render` wrote for `manifest`, taken from the GitHub workflow.
    fn new(manifest: &str) -> Stage {
        let root = repository(manifest, &[]);
        render(root.path(), false).unwrap();
        let script = github_script(&read(root.path(), ".github/workflows/pr-check.yml"));
        let tool_source = script
            .lines()
            .find_map(|line| line.strip_prefix("CHECK_TOOL_SOURCE='"))
            .and_then(|rest| rest.strip_suffix('\''))
            .unwrap()
            .to_owned();
        let dir = tempfile::tempdir().unwrap();
        for sub in ["fix/packages", "bin", "home", "checkout"] {
            fs::create_dir_all(dir.path().join(sub)).unwrap();
        }
        let curl = dir.path().join("bin/curl");
        fs::copy("tests/it/fixtures/mirror-check-fake-curl", &curl).unwrap();
        fs::set_permissions(&curl, fs::Permissions::from_mode(0o755)).unwrap();
        Stage::program(
            &dir.path().join("bin/nix-store"),
            "echo \"$*\" >> \"$FIX/nix-store.log\"\n[ ! -f \"$FIX/nix-store.fail\" ]",
        );
        Stage {
            dir,
            script,
            tool_source,
        }
    }

    fn program(path: &Path, body: &str) {
        fs::write(path, format!("#!/bin/sh\n{body}\n")).unwrap();
        fs::set_permissions(path, fs::Permissions::from_mode(0o755)).unwrap();
    }

    fn fix(&self) -> PathBuf {
        self.dir.path().join("fix")
    }

    /// A ccid release `revision` whose binary logs its arguments and exits as the test says; returns its sha256.
    fn release(&self, revision: &str, extra: &str) -> String {
        let body = format!(
            "#!/bin/sh\n# {extra}\necho \"$*\" >> \"$FIX/ccid.log\"\n[ \"${{CCID_TEST_READS_STDIN:-}}\" = 1 ] && cat > /dev/null\n[ ! -f \"$FIX/ccid.fail.$4\" ]\n"
        );
        fs::write(self.fix().join("packages").join(revision), &body).unwrap();
        sha(body.as_bytes())
    }

    /// The release channel as the forge publishes it: the real `channel.json` of this repository with the
    /// releases replaced, so the script parses a file shaped like the real one.
    fn channel(&self, default: (&str, &str), linux: Option<(&str, &str)>) {
        let mut channel: serde_json::Value =
            serde_json::from_slice(&fs::read("channel.json").unwrap()).unwrap();
        channel["default"] = json!({"revision": default.0, "sha256": default.1});
        match linux {
            Some((revision, sha256)) => {
                channel["classes"] = json!({"linux": {"revision": revision, "sha256": sha256}});
            }
            None => {
                channel.as_object_mut().unwrap().remove("classes");
            }
        }
        fs::write(
            self.fix().join("channel.json"),
            serde_json::to_string_pretty(&channel).unwrap(),
        )
        .unwrap();
    }

    fn run(&self, env: &[(&str, &str)]) -> Outcome {
        let path = format!(
            "{}:{}",
            self.dir.path().join("bin").display(),
            std::env::var("PATH").unwrap()
        );
        let mut child = Command::new("sh")
            .arg("-s")
            .env_clear()
            .env("PATH", path)
            .env("HOME", self.dir.path().join("home"))
            .env("TMPDIR", self.dir.path())
            .env("FIX", self.fix())
            .env("TOOL_SOURCE", &self.tool_source)
            .envs(env.iter().copied())
            .current_dir(self.dir.path().join("checkout"))
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .unwrap();
        // The script arrives on stdin, as it does in the container: what runs must not read the rest of it.
        use std::io::Write;
        child
            .stdin
            .take()
            .unwrap()
            .write_all(self.script.as_bytes())
            .unwrap();
        let output = child.wait_with_output().unwrap();
        Outcome {
            code: output.status.code().unwrap(),
            stderr: String::from_utf8_lossy(&output.stderr).into_owned(),
        }
    }

    fn log(&self, name: &str) -> String {
        fs::read_to_string(self.fix().join(name)).unwrap_or_default()
    }
}

const D: &str = "dddddddddddddddddddddddddddddddddddddddd";
