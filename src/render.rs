    #[test]
    fn template_variable_set_is_pinned() {
        let template = include_str!("render/crow.yaml");
        let section = template
            .split_once("variables:")
            .expect("template has a variables section");
        let section = section
            .1
            .split_once("steps:")
            .expect("template has steps")
            .0;
        let mut names = Vec::new();
        for line in section.lines() {
            let Some(declaration) = line.strip_prefix("  ") else {
                continue;
            };
            let Some((name, default)) = declaration.split_once(": {default: ") else {
                continue;
            };
            if !name.is_empty()
                && name
                    .bytes()
                    .all(|byte| byte.is_ascii_uppercase() || byte == b'_' || byte.is_ascii_digit())
                && default.starts_with('"')
                && default.ends_with('}')
            {
                names.push(name.to_owned());
            }
        }
        names.sort();
        let mut expected: Vec<String> =
            TEMPLATE_VARIABLES.iter().map(ToString::to_string).collect();
        expected.sort();
        assert_eq!(names, expected);
    }

