/// Render one workflow adapter, appending declared auxiliary variables that
/// apply to it. Output is byte-identical to the plain template when none apply.
fn workflow_adapter(
    crow: &str,
    tool_revision: &str,
    workflow: &str,
    sources: &BTreeMap<String, PinnedSource>,
) -> Result<String> {
    let template = crow.replace("CCID_TOOL_REVISION", tool_revision);
    let mut extra = Vec::new();
    for source in sources.values() {
        if let Some(workflows) = &source.workflows {
            if !workflows.iter().any(|name| name == workflow) {
                continue;
            }
        }
        extra.push(format!("  {}: {{default: \"\"}}", source.archive_variable));
        extra.push(format!("  {}: {{default: \"\"}}", source.digest_variable));
    }
    if extra.is_empty() {
        return Ok(template);
    }
    let (head, tail) = template
        .split_once("\nsteps:")
        .ok_or_else(|| failure("Adapter template has no steps section"))?;
    Ok(format!("{head}\n{}\nsteps:{tail}", extra.join("\n")))
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Config {
    /// The exact ccid release the generated adapters are pinned to. Absent in a repository on `render_schema = 2`, which
    /// takes the release from the central channel the runner names (no push per bump).
    #[serde(default)]
    pub tool_revision: String,
    /// 2: Forgejo workflows carry a short stable shim that finds the centrally chosen ccid and runs `ccid job-run`; the repository pins no release.
    /// 3: as 2, and ccid owns the repository's whole CI surface (`surface`): verdict jobs run per commit, other jobs by
    /// hand, labels are `linux`, `windows` or `macos`, retired CI files go and unknown ones are refused.
    #[serde(default)]
    pub render_schema: Option<u32>,
    /// Crow repo secret holding the immutable prebuilt tool path.
    #[serde(default = "default_tool_secret_binary")]
    pub tool_secret_binary: String,
    /// Crow repo secret holding the tool path's sha256.
    #[serde(default = "default_tool_secret_binary_sha256")]
    pub tool_secret_binary_sha256: String,
    /// Optional resolver credential projection.
    ///
    /// When present, render adds ONLY this fixed entry to the repository-job
    /// step environment (never to native-status steps):
    /// `CFRG_RESOLVER_FORGEJO_TOKEN: { from_secret: <name> }`.
    /// This is a secret *reference* (name only); values are never embedded.
    /// Absent by default: rendered output is byte-identical to the unopted
    /// template. The referenced repository secret must already be configured
    /// for the selected repository; ccid never distributes tokens fleet-wide.
    /// Contribution checks (no secret configured) render unchanged.
    /// No operator hostnames appear here.
    #[serde(default)]
    pub resolver_token_secret: Option<String>,
    /// Crow repository secrets projected as environment variables into the
    /// repository-job step: `NAME = "<crow secret>"`. Only a job that lists
    /// `NAME` in its own `secrets` sees the value; `execute` withholds it from
    /// every other job. Secret references (names only) are rendered, values
    /// never. Native-status steps never carry them. Empty by default: rendered
    /// output is byte-identical to the unopted template.
    #[serde(default)]
    pub secret_environment: BTreeMap<String, String>,
    /// Forgejo workflows: lowercase hex sha256 of the pinned tool release for this
    /// platform. A runner that lacks the declared tool may fetch it by hash.
    #[serde(default)]
    pub tool_sha256: Option<String>,
    /// Crow is retired as a scheduler: this renderer refuses Crow jobs, Crow
    /// push adapters and push-consumer fan-out unless the manifest says so.
    /// The escape hatch exists for repositories that have not moved yet.
    #[serde(default)]
    pub allow_crow: bool,
}

/// The render form a manifest's `render_schema` selects.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Schema {
    /// No `render_schema`: the repository pins its own ccid release.
    Pinned,
    /// `render_schema = 2`: the central channel chooses the release.
    Central,
    /// `render_schema = 3`: as 2, and ccid owns the whole CI surface.
    Surface,
}

impl Schema {
    fn of(config: &Config) -> Result<Schema> {
        match config.render_schema {
            None => Ok(Schema::Pinned),
            Some(2) => Ok(Schema::Central),
            Some(3) => Ok(Schema::Surface),
            Some(other) => Err(failure(format!(
                "[render].render_schema {other} is not supported by this ccid (supported: 2, 3)"
            ))),
        }
    }

    fn central(self) -> bool {
        self != Schema::Pinned
    }
}

/// The `[render]` table's own rules, before anything is rendered.
fn validate_config(config: &Config, schema: Schema) -> Result<()> {
    if schema.central() {
        if !config.tool_revision.is_empty() || config.tool_sha256.is_some() {
            return Err(failure(format!(
                "A repository on render_schema = {} pins no release: remove [render].tool_revision and tool_sha256 (the central channel chooses)",
                if schema == Schema::Surface { 3 } else { 2 }
            )));
        }
    } else if config.tool_revision.len() != 40
        || !config
            .tool_revision
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
    {
        return Err(failure(
            "Rendered tool revision must be a full lowercase Git SHA",
        ));
    }
    if schema == Schema::Surface && config.allow_crow {
        return Err(failure(
            "render_schema = 3 has no Crow: remove [render].allow_crow",
        ));
    }
    if let Some(secret) = config.resolver_token_secret.as_deref() {
        validate_resolver_token_secret(secret)?;
    }
    validate_secret_environment(&config.secret_environment)?;
    if let Some(digest) = &config.tool_sha256 {
        if digest.len() != 64
            || !digest
                .bytes()
                .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
        {
            return Err(failure(
                "[render].tool_sha256 must be 64 lowercase hex digits",
            ));
        }
    }
    Ok(())
}

/// A job's schema-3 form: Forgejo only, a known label (default `linux`), a verdict job on every commit, every
/// other job by hand unless it names its events.
fn surface_job(plan: &mut jobs::Plan, verdict: bool) -> Result<()> {
    match plan.scheduler {
        jobs::Scheduler::Forgejo => {}
        jobs::Scheduler::Remote => {
            return Err(failure(format!(
                "render_schema = 3 has no remote scheduler: [jobs.{}] becomes a Forgejo job on the windows or macos label, an evaluation on linux (aarch64), or goes",
                plan.job
            )))
        }
        other => {
            return Err(failure(format!(
                "render_schema = 3 runs Forgejo jobs only: [jobs.{}] has scheduler = \"{}\"",
                plan.job,
                format!("{other:?}").to_lowercase()
            )))
        }
    }
    match plan.runs_on.as_deref() {
        None => plan.runs_on = Some(surface::DEFAULT_LABEL.to_owned()),
        Some(label) if surface::LABELS.contains(&label) => {}
        Some(label) => {
            return Err(failure(format!(
                "render_schema = 3 knows the runner labels {} only: [jobs.{}] asks for {label}",
                surface::LABELS.join(", "),
                plan.job
            )))
        }
    }
    if verdict {
        if !plan.events.is_empty() {
            return Err(failure(format!(
                "At render_schema = 3 a verdict job runs on every push, every pull request and by hand: remove events from [jobs.{}]",
                plan.job
            )));
        }
    } else if plan.events.is_empty() {
        plan.events = vec!["manual".to_owned()];
    }
    Ok(())
}

fn default_tool_secret_binary() -> String {
    "CI_TOOL_BINARY_STATIC".into()
}

fn default_tool_secret_binary_sha256() -> String {
    "CI_TOOL_BINARY_SHA256_STATIC".into()
}

fn validate_secret_name(value: &str) -> Result<()> {
    if value.is_empty()
        || value.contains("CCID")
        || !value
            .bytes()
            .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == b'_')
    {
        return Err(failure(
            "Tool secret names must be plain uppercase identifiers",
        ));
    }
    Ok(())
}

/// A dependency push fan-out declaration: this repository's push events run
/// the consumer's repository-owned job with the event commit pinned.
#[derive(Debug, Deserialize, Serialize, Clone)]
#[serde(deny_unknown_fields)]
pub struct PushConsumer {
    /// Consumer forge URL (https, ssh, or scp-like; never credentials).
    pub consumer: String,
    /// This repository's branch whose pushes trigger the consumer run.
    pub branch: String,
    /// Consumer branch fetched and executed.
    pub consumer_branch: String,
    /// Consumer job name executed for the event.
    pub job: String,
    /// This repository's package name inside the consumer graph.
    pub self_name: String,
}

#[derive(Debug, Serialize)]
struct ConsumerPlan {
    consumer: String,
    branch: String,
    consumer_branch: String,
    job: String,
    self_name: String,
}

const RESOLVER_TOKEN_ENV: &str = "CFRG_RESOLVER_FORGEJO_TOKEN";

#[derive(Debug, Serialize)]
pub struct Report {
    pub checked: bool,
    pub files: Vec<PathBuf>,
    pub removed: Vec<PathBuf>,
    /// `--check` only: files accepted as the previous body of a declared
    /// template transition; the next render updates them.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub transitional: Vec<PathBuf>,
    /// `render_schema = 3`: the verdict jobs the mirror platforms do not run, each with its reason.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub forge_only: Vec<String>,
}

#[derive(Serialize)]
struct Inventory<'a> {
    schema: u32,
    generator: &'static str,
    tool_revision: &'a str,
    manifest_sha256: String,
    jobs: BTreeMap<String, jobs::Plan>,
    /// Fan-out declarations; skipped when empty so manual-only inventories
    /// render byte-identical to before.
    #[serde(skip_serializing_if = "BTreeMap::is_empty")]
    push_consumers: BTreeMap<String, ConsumerPlan>,
}

/// The provider workflow file a remote declaration refers to inside the
/// repository mirror. The broker runs it; ccid only requires that it exists.
fn remote_workflow_path(provider: jobs::Provider, workflow: &str) -> String {
    match provider {
        jobs::Provider::Github => format!(".github/workflows/{workflow}.yml"),
        jobs::Provider::Gitlab => ".gitlab-ci.yml".to_owned(),
        jobs::Provider::Circleci => ".circleci/config.yml".to_owned(),
        jobs::Provider::Bitbucket => "bitbucket-pipelines.yml".to_owned(),
    }
}

/// The files one render writes, from `templates`. Pure apart from reading the
/// repository's declared inputs; `render` validates `config` before.
fn render_outputs(
    repo: &Path,
    manifest: &Path,
    parsed: &crate::Manifest,
    bytes: &[u8],
    config: &Config,
    schema: Schema,
    templates: &Templates,
) -> Result<BTreeMap<PathBuf, String>> {
    let central = schema.central();
    let mut inventory = Inventory {
        schema: 1,
        generator: GENERATOR,
        tool_revision: &config.tool_revision,
        manifest_sha256: format!("{:x}", Sha256::digest(bytes)),
        jobs: BTreeMap::new(),
        push_consumers: BTreeMap::new(),
    };
    let mut sources = pinned_sources(repo)?;
    for (name, source) in live_inputs(repo)? {
        if sources.insert(name.clone(), source).is_some() {
            return Err(failure(format!(
                "Live input name collides with a pinned source: {name}"
            )));
        }
    }
    let mut outputs = BTreeMap::new();
    let gating = gating_jobs(parsed)?;
    if schema == Schema::Surface {
        if gating.is_empty() {
            return Err(failure(
                "render_schema = 3 verifies every commit: declare [jobs.verify] or [verdict] jobs",
            ));
        }
        if !parsed.push_consumer.is_empty() {
            return Err(failure(
                "render_schema = 3 has no Crow push_consumer fan-out: remove the push_consumer entries",
            ));
        }
    }
    let _ = manifest;
    for name in parsed.jobs.keys() {
        let mut plan = jobs::plan_parsed(parsed, name, None)?;
        if schema == Schema::Surface {
            surface_job(&mut plan, gating.contains(name))?;
        } else if plan.mirror_optout.is_some() {
            return Err(failure(format!(
                "[jobs.{name}] mirror = false belongs to render_schema = 3 (the mirror platforms' checks)"
            )));
        }
        if plan.scheduler == jobs::Scheduler::Remote {
            // Remote jobs are dispatched by the host-side broker, which runs
            // the provider's own workflow; ccid only records the declaration.
            // The workflow file must already exist in the repository.
            let provider = plan
                .provider
                .ok_or_else(|| failure(format!("Remote job {name}: missing provider")))?;
            let path = remote_workflow_path(provider, &plan.workflow);
            if !repo.join(&path).is_file() {
                return Err(failure(format!(
                    "Remote job {name}: provider workflow file {path} is missing"
                )));
            }
            inventory.jobs.insert(name.clone(), plan);
            continue;
        }
        if plan.scheduler == jobs::Scheduler::Forgejo {
            // Forgejo jobs get a native workflow below, never a Crow adapter.
            inventory.jobs.insert(name.clone(), plan);
            continue;
        }
        outputs.insert(
            PathBuf::from(format!(".crow/{}.yaml", plan.workflow)),
            inject_gating(
                inject_secret_environment(
                    inject_resolver_token(
                        workflow_adapter(
                            templates.crow,
                            &config.tool_revision,
                            &plan.workflow,
                            &sources,
                        )?,
                        &config.tool_revision,
                        config.resolver_token_secret.as_deref(),
                    )?,
                    &config.tool_revision,
                    &config.secret_environment,
                )?,
                &gating,
            )?,
        );
        inventory.jobs.insert(name.clone(), plan);
    }
    if central
        && inventory.jobs.values().any(|plan| {
            plan.scheduler != jobs::Scheduler::Forgejo && plan.scheduler != jobs::Scheduler::Remote
        })
    {
        return Err(failure(
            "render_schema = 2 supports Forgejo and remote jobs only",
        ));
    }
    if !config.allow_crow {
        let crow_jobs: Vec<&str> = inventory
            .jobs
            .iter()
            .filter(|(_, plan)| plan.scheduler == jobs::Scheduler::Crow)
            .map(|(name, _)| name.as_str())
            .collect();
        if !crow_jobs.is_empty() || !parsed.push_consumer.is_empty() {
            return Err(failure(format!(
                "Crow is retired as a scheduler: jobs {crow_jobs:?}{} need scheduler = \"forgejo\" (or [render] allow_crow = true until the repository moves)",
                if parsed.push_consumer.is_empty() {
                    ""
                } else {
                    " and push_consumer entries (no Forgejo fan-out exists yet)"
                }
            )));
        }
    }
    // Push adapters are keyed per job and branch so the event carries no job
    // selection: the filename and baked command name it. Only opted-in jobs
    // take the filename rules; manual-only jobs keep their existing names.
    // The CCID_ prefix is reserved so substituted values can never
    // reintroduce a placeholder. Secret validation runs only when push
    // files are actually emitted, so manual-only manifests never see it.
    let repository = parsed
        .repository
        .as_deref()
        .filter(|url| !url.contains("CCID") && crate::cache::canonical_repository(url).is_ok());
    for name in parsed.jobs.keys() {
        let planned = jobs::plan_parsed(parsed, name, None)?;
        if planned.scheduler == jobs::Scheduler::Forgejo
            || planned.scheduler == jobs::Scheduler::Remote
            || planned.push_branches.is_empty()
        {
            continue;
        }
        validate_push_name(name)?;
        validate_secret_name(&config.tool_secret_binary)?;
        validate_secret_name(&config.tool_secret_binary_sha256)?;
        let consumer =
            repository.ok_or_else(|| failure("Push adapters require a manifest repository URL"))?;
        for branch in &planned.push_branches {
            let filename = format!(".crow/push-{name}-{branch}.yaml");
            if outputs.contains_key(&PathBuf::from(&filename)) {
                return Err(failure(format!("Duplicate push adapter: {filename}")));
            }
            outputs.insert(
                PathBuf::from(filename),
                substitute(
                    templates.push,
                    config,
                    &[
                        ("CCID_PUSH_BRANCH", branch.as_str()),
                        ("CCID_PUSH_JOB", name.as_str()),
                        ("CCID_CONSUMER_URL", consumer),
                    ],
                ),
            );
        }
    }
    for (name, consumer) in &parsed.push_consumer {
        validate_push_name(name)?;
        validate_secret_name(&config.tool_secret_binary)?;
        validate_secret_name(&config.tool_secret_binary_sha256)?;
        let entry = validate_consumer(consumer)?;
        // The dependency's own canonical repository is the trigger source:
        // bake it so dep events carry repository+branch+sha provenance, not a
        // bare package name.
        let trigger_repo =
            repository.ok_or_else(|| failure("Push adapters require a manifest repository URL"))?;
        let filename = format!(".crow/push-consumer-{name}.yaml");
        if outputs.contains_key(&PathBuf::from(&filename)) {
            return Err(failure(format!("Duplicate push adapter: {filename}")));
        }
        outputs.insert(
            PathBuf::from(filename),
            substitute(
                templates.consumer,
                config,
                &[
                    ("CCID_DEP_BRANCH", entry.branch.as_str()),
                    ("CCID_CONSUMER_URL", entry.consumer.as_str()),
                    ("CCID_CONSUMER_BRANCH", entry.consumer_branch.as_str()),
                    ("CCID_CONSUMER_JOB", entry.job.as_str()),
                    ("CCID_DEP_NAME", entry.self_name.as_str()),
                    ("CCID_DEP_REPO", trigger_repo),
                ],
            ),
        );
        inventory.push_consumers.insert(
            name.clone(),
            ConsumerPlan {
                consumer: entry.consumer.clone(),
                branch: entry.branch.clone(),
                consumer_branch: entry.consumer_branch.clone(),
                job: entry.job.clone(),
                self_name: entry.self_name.clone(),
            },
        );
    }
    let mut forgejo: BTreeMap<&str, Vec<&jobs::Plan>> = BTreeMap::new();
    for plan in inventory.jobs.values() {
        if plan.scheduler == jobs::Scheduler::Forgejo {
            forgejo
                .entry(plan.workflow.as_str())
                .or_default()
                .push(plan);
        }
    }
    for (workflow, plans) in &forgejo {
        if schema == Schema::Surface
            && plans.iter().any(|plan| gating.contains(&plan.job))
            && plans.iter().any(|plan| !gating.contains(&plan.job))
        {
            return Err(failure(format!(
                "At render_schema = 3 verdict jobs run per commit and other jobs by hand: workflow {workflow} mixes them, so give the other jobs their own workflow (or list them in [verdict] jobs)"
            )));
        }
        if plans.iter().any(|plan| plan.events != plans[0].events) {
            return Err(failure(format!(
                "Forgejo jobs of workflow {workflow} must declare the same events"
            )));
        }
        outputs.insert(
            PathBuf::from(format!("{FORGEJO_DIRECTORY}/{workflow}.yml")),
            if central {
                forgejo_workflow_central(templates, workflow, plans)
            } else {
                forgejo_workflow(
                    templates,
                    &config.tool_revision,
                    config.tool_sha256.as_deref(),
                    workflow,
                    plans,
                )
            },
        );
    }
    outputs.insert(
        PathBuf::from(INVENTORY),
        serde_json::to_string_pretty(&inventory)? + "\n",
    );
    if parsed.check_shell.is_some() {
        outputs.insert(PathBuf::from(CHECK_SHELL), templates.check_shell.to_owned());
    }
    // render_schema = 3: the mirror platforms also run the repository's verdict jobs for a pull request or
    // a merge request. Schemas 1 and 2 render the release mirror alone, byte for byte as before.
    let checks = if schema == Schema::Surface {
        Some(mirror_checks(&inventory.jobs, &gating, parsed))
    } else {
        None
    };
    if let Some(source) = mirror::source(repo, parsed.repository.as_deref()) {
        outputs.extend(mirror::outputs(
            repo,
            &source,
            templates,
            schema == Schema::Surface,
            checks.as_ref(),
        )?);
    }
    if let Some(checks) = &checks {
        if let Some(workflow) = mirror::github_check(templates, checks)? {
            outputs.insert(PathBuf::from(mirror::GITHUB_CHECK), workflow);
        }
    }
    outputs.extend(upstream_sync::outputs(repo, &inventory.jobs, templates)?);
    Ok(outputs)
}

/// The verdict jobs that run on the mirror platforms' own compute and those that stay on the forge.
fn mirror_checks(
    plans: &BTreeMap<String, jobs::Plan>,
    gating: &[String],
    parsed: &crate::Manifest,
) -> mirror::Checks {
    let fork = parsed
        .surface
        .as_ref()
        .is_some_and(|surface| !surface.upstream.is_empty());
    mirror::Checks::of(plans, gating, fork)
}

/// The `render` and `render --check` notices for the verdict jobs that stay on the forge only.
fn forge_only_notices(parsed: &crate::Manifest, schema: Schema) -> Result<Vec<String>> {
    if schema != Schema::Surface {
        return Ok(Vec::new());
    }
    let gating = gating_jobs(parsed)?;
    let mut plans = BTreeMap::new();
    for name in parsed.jobs.keys() {
        let mut plan = jobs::plan_parsed(parsed, name, None)?;
        surface_job(&mut plan, gating.contains(name))?;
        plans.insert(name.clone(), plan);
    }
    Ok(mirror_checks(&plans, &gating, parsed).notices())
}

/// Why `job` is not a mirror check of the manifest in `repo` (`ccid job-run --mirror` refuses it), or
/// none when it is one: a verdict job that `forge_only_reason` accepts.
pub(crate) fn mirror_refusal(repo: &Path, manifest: &Path, job: &str) -> Result<Option<String>> {
    let (parsed, _) = load_manifest(repo, manifest)?;
    let plan = jobs::plan_parsed(&parsed, job, None)?;
    if !gating_jobs(&parsed)?.iter().any(|name| name == job) {
        return Ok(Some("it is not a verdict job".to_owned()));
    }
    if parsed
        .surface
        .as_ref()
        .is_some_and(|surface| !surface.upstream.is_empty())
    {
        return Ok(Some(
            "this repository lists upstream CI files (a fork)".to_owned(),
        ));
    }
    Ok(mirror::forge_only_reason(&plan))
}

/// Render repository jobs, or check byte-for-byte drift without modifying files.
/// Manual Crow execution adapters come from job workflows; push execution
/// adapters come from job push opt-ins and consumer fan-out declarations.
pub fn render(repo: &Path, manifest: &Path, check: bool) -> Result<Report> {
    // execute-job reads this exact path from its verified source archive.
    if manifest != Path::new(".ci/ccid.toml") {
        return Err(failure("Job adapters require .ci/ccid.toml"));
    }
    let (parsed, bytes) = load_manifest(repo, manifest)?;
    let config = parsed
        .render
        .as_ref()
        .ok_or_else(|| failure("Manifest requires [render].tool_revision"))?;
    let schema = Schema::of(config)?;
    validate_config(config, schema)?;
    if parsed.jobs.is_empty() {
        return Err(failure("Rendering requires at least one declared job"));
    }
    let outputs = render_outputs(
        repo,
        manifest,
        &parsed,
        &bytes,
        config,
        schema,
        &Templates::CURRENT,
    )?;
    let forge_only = forge_only_notices(&parsed, schema)?;
    for notice in &forge_only {
        eprintln!("ccid render: {notice}");
    }
    // render_schema = 3: every CI file is classified before anything is written; a refused file stops the render.
    let surface = if schema == Schema::Surface {
        let known = mirror::source(repo, parsed.repository.as_deref()).is_some();
        let entries = surface::assess(repo, &parsed, &outputs, known)?;
        if let Some(message) = surface::refusal(&entries) {
            return Err(failure(message));
        }
        Some(entries)
    } else {
        None
    };
    let replaced: Vec<&Path> = surface
        .iter()
        .flatten()
        .filter(|item| {
            item.class == surface::Class::Legacy && item.action == surface::Action::Write
        })
        .map(|item| item.path.as_path())
        .collect();

    // Validate the whole destination set before any writes or directory creation.
    for directory in [".ci", ".crow", ".forgejo", ".github"] {
        if let Some(metadata) = metadata(&repo.join(directory))? {
            if !metadata.is_dir() || metadata.file_type().is_symlink() {
                return Err(failure(format!("Unsafe adapter directory: {directory}")));
            }
        }
    }
    let mut drift = Vec::new();
    let mut committed = BTreeMap::new();
    for (relative, expected) in &outputs {
        let path = repo.join(relative);
        if let Some(metadata) = metadata(&path)? {
            if !metadata.is_file() || metadata.file_type().is_symlink() {
                return Err(failure(format!(
                    "Unsafe adapter file: {}",
                    relative.display()
                )));
            }
            let actual = fs::read_to_string(path)?;
            if !owned(relative, &actual) && !replaced.contains(&relative.as_path()) {
                return Err(failure(format!(
                    "Refusing to overwrite foreign adapter: {}",
                    relative.display()
                )));
            }
            if actual != *expected {
                drift.push(relative.clone());
                committed.insert(relative.clone(), actual);
            }
        } else {
            drift.push(relative.clone());
        }
    }
    let obsolete = match &surface {
        None => obsolete(repo, &outputs)?,
        Some(entries) => entries
            .iter()
            .filter(|item| item.action == surface::Action::Delete)
            .map(|item| item.path.clone())
            .collect(),
    };
    // Legacy files a check names with what replaces them.
    let legacy: BTreeMap<&Path, &str> = surface
        .iter()
        .flatten()
        .filter(|item| item.class == surface::Class::Legacy)
        .filter_map(|item| Some((item.path.as_path(), item.replacement?)))
        .collect();
    // A check accepts the absence of a file this release introduced; the next render writes it.
    let mut transitional = Vec::new();
    if check {
        let mut kept = Vec::new();
        for relative in drift {
            if (mirror::introduced(&relative) || upstream_sync::introduced(&relative))
                && metadata(&repo.join(&relative))?.is_none()
            {
                eprintln!(
                    "ccid render: {} is introduced by this release (a declared transition); the next render writes it",
                    relative.display()
                );
                transitional.push(relative);
            } else {
                kept.push(relative);
            }
        }
        drift = kept;
    }
    // A check accepts a file this release renders from a declared transition's previous body.
    if check && !committed.is_empty() {
        let accepted = transitions(&committed, |templates| {
            render_outputs(repo, manifest, &parsed, &bytes, config, schema, templates)
        })?;
        for (relative, declared) in &accepted {
            let from: Vec<String> = declared
                .iter()
                .map(|transition| {
                    format!(
                        "{} of {}",
                        transition.template.file(),
                        &transition.since[..transition.since.len().min(10)]
                    )
                })
                .collect();
            eprintln!(
                "ccid render: {} is rendered from the previous {} (a declared transition); the next render updates it",
                relative.display(),
                from.join(" and ")
            );
        }
        drift.retain(|relative| !accepted.contains_key(relative));
        transitional.extend(accepted.into_keys());
        transitional.sort();
    }
    if fs::read(repo.join(manifest))? != bytes {
        return Err(failure("Manifest changed during job rendering"));
    }
    if check && (!drift.is_empty() || !obsolete.is_empty()) {
        let paths = drift
            .iter()
            .chain(&obsolete)
            .map(|path| match legacy.get(path.as_path()) {
                Some(replacement) => {
                    format!(
                        "{} (retired, render removes it: {replacement})",
                        path.display()
                    )
                }
                None => path.display().to_string(),
            })
            .collect::<Vec<_>>()
            .join(", ");
        return Err(failure(format!(
            "Generated job adapters have drifted: {paths}"
        )));
    }
    if !check {
        for relative in &drift {
            let path = repo.join(relative);
            let parent = path
                .parent()
                .expect("Generated paths have parent directories");
            fs::create_dir_all(parent)?;
            let mut temporary = tempfile::NamedTempFile::new_in(parent)?;
            temporary.write_all(outputs[relative].as_bytes())?;
            temporary.persist(path)?;
        }
        for relative in &obsolete {
            fs::remove_file(repo.join(relative))?;
        }
    }
    Ok(Report {
        checked: check,
        files: outputs.into_keys().collect(),
        removed: obsolete,
        transitional,
        forge_only,
    })
}

/// `ccid surface report`: every CI file of the repository, its class and what a `render_schema = 3` render does
/// with it. A repository on an older schema is classified against the files its own schema renders.
pub fn surface_report(repo: &Path, manifest: &Path) -> Result<surface::Report> {
    if manifest != Path::new(".ci/ccid.toml") {
        return Err(failure("Job adapters require .ci/ccid.toml"));
    }
    let (parsed, bytes) = load_manifest(repo, manifest)?;
    let config = parsed
        .render
        .as_ref()
        .ok_or_else(|| failure("Manifest requires [render]"))?;
    let schema = Schema::of(config)?;
    validate_config(config, schema)?;
    let outputs = render_outputs(
        repo,
        manifest,
        &parsed,
        &bytes,
        config,
        schema,
        &Templates::CURRENT,
    )?;
    let known = mirror::source(repo, parsed.repository.as_deref()).is_some();
    Ok(surface::Report {
        render_schema: config.render_schema,
        files: surface::assess(repo, &parsed, &outputs, known)?,
    })
}

/// `ccid surface plan` of one repository: the manifest's mechanical `render_schema = 3` edits, applied in memory,
/// and what a render of the edited manifest writes, deletes, keeps and refuses. Never writes; a failure is recorded.
pub fn surface_plan(repo: &Path, manifest: &Path) -> surface::Plan {
    let mut plan = surface::Plan {
        repo: repo.to_path_buf(),
        ..surface::Plan::default()
    };
    let result = (|| -> Result<()> {
        if manifest != Path::new(".ci/ccid.toml") {
            return Err(failure("Job adapters require .ci/ccid.toml"));
        }
        let bytes = fs::read(repo.join(manifest))?;
        let mut value: toml::Value = toml::from_str(std::str::from_utf8(&bytes)?)?;
        plan.project = value
            .get("project")
            .and_then(toml::Value::as_str)
            .map(str::to_owned);
        plan.render_schema = value
            .get("render")
            .and_then(|render| render.get("render_schema"))
            .and_then(toml::Value::as_integer);
        // The repository's manifest must parse as it is before the plan edits it.
        crate::parse_manifest(&bytes)?;
        let (edits, decisions, notes) = surface::align(&mut value);
        plan.edits = edits;
        plan.decisions = decisions;
        plan.notes = notes;
        let edited = toml::to_string(&value)?;
        let parsed = crate::parse_manifest(edited.as_bytes())?;
        let config = parsed
            .render
            .as_ref()
            .ok_or_else(|| failure("Manifest requires [render]"))?;
        validate_config(config, Schema::Surface)?;
        if parsed.jobs.is_empty() {
            return Err(failure("Rendering requires at least one declared job"));
        }
        let outputs = render_outputs(
            repo,
            manifest,
            &parsed,
            edited.as_bytes(),
            config,
            Schema::Surface,
            &Templates::CURRENT,
        )?;
        let known = mirror::source(repo, parsed.repository.as_deref()).is_some();
        let entries = surface::assess(repo, &parsed, &outputs, known)?;
        plan.writes = outputs
            .iter()
            .filter(|(relative, body)| {
                fs::read(repo.join(relative)).ok().as_deref() != Some(body.as_bytes())
            })
            .map(|(relative, _)| relative.clone())
            .collect();
        plan.settle(entries);
        Ok(())
    })();
    if let Err(error) = result {
        plan.error = Some(error.to_string());
    }
    plan.finish();
    plan
}

/// The committed files that equal a render with some combination of declared
/// transitions in place, each with the transitions of its first match.
fn transitions(
    committed: &BTreeMap<PathBuf, String>,
    render: impl Fn(&Templates) -> Result<BTreeMap<PathBuf, String>>,
) -> Result<BTreeMap<PathBuf, Vec<&'static Transition>>> {
    let mut accepted: BTreeMap<PathBuf, Vec<&'static Transition>> = BTreeMap::new();
    for mask in 1u32..(1 << TRANSITIONS.len()) {
        if accepted.len() == committed.len() {
            break;
        }
        let declared: Vec<&'static Transition> = TRANSITIONS
            .iter()
            .enumerate()
            .filter(|(index, _)| mask & (1 << index) != 0)
            .map(|(_, transition)| transition)
            .collect();
        let templates = declared
            .iter()
            .fold(Templates::CURRENT, |templates, transition| {
                templates.with(transition.template, transition.previous)
            });
        let rendered = render(&templates)?;
        for (relative, actual) in committed {
            if !accepted.contains_key(relative) && rendered.get(relative) == Some(actual) {
                accepted.insert(relative.clone(), declared.clone());
            }
        }
    }
    Ok(accepted)
}

/// Shell that stages a job's declared sibling repositories, read-only, as
/// `<checkout>.siblings/<name>`, with the same fetch discipline as the
/// checkout (a few attempts against the runner's local copy, then against the
/// forge itself). It exports `CCID_SIBLINGS_DIR` and the resolved commits as
/// `CCID_SIBLINGS_REVISIONS` (`name=sha,...`, a stable cache-key input).
/// Empty for a job that declares none, so existing workflows stay byte-identical.
fn forgejo_siblings_step(siblings: &BTreeMap<String, String>) -> String {
    if siblings.is_empty() {
        return String::new();
    }
    let indent = "\n          ";
    let mut lines: Vec<String> = vec![
        "# Sibling repositories declared by the job, read-only, at their pinned or default-branch revisions.".into(),
        "siblings_dir=\"$PWD.siblings\"".into(),
        "if [ -e \"$siblings_dir\" ]; then rm -r \"$siblings_dir\"; fi".into(),
        "mkdir -p \"$siblings_dir\"".into(),
        "siblings_revisions=".into(),
        "stage_sibling() {".into(),
        "  name=$1; repo=$2; want=$3".into(),
        "  dir=\"$siblings_dir/$name\"; mkdir -p \"$dir\"".into(),
        "  git -C \"$dir\" init --quiet".into(),
        "  git -C \"$dir\" remote add origin \"${{ github.server_url }}/$repo.git\"".into(),
        "  ref=$want; [ \"$want\" != main ] || ref=HEAD".into(),
        "  sib_fetch() { git -C \"$dir\" -c \"http.extraHeader=Authorization: token $CCID_FORGE_TOKEN\" fetch --quiet --depth 1 origin \"$ref\"; }".into(),
        "  got=".into(),
        "  for attempt in 1 2 3; do".into(),
        "    if sib_fetch; then got=1; break; fi".into(),
        "    [ \"$attempt\" -lt 3 ] && sleep 5".into(),
        "  done".into(),
        "  if [ -z \"$got\" ]; then".into(),
        "    echo \"local copy lacks $repo $want, fetching from the forge\" >&2".into(),
        "    for attempt in 1 2 3; do".into(),
        "      if GIT_CONFIG_SYSTEM=/dev/null GIT_CONFIG_COUNT=0 sib_fetch; then got=1; break; fi".into(),
        "      [ \"$attempt\" -lt 3 ] && sleep 5".into(),
        "    done".into(),
        "  fi".into(),
        "  [ -n \"$got\" ] || { echo \"cannot fetch sibling $repo $want\" >&2; exit 2; }".into(),
        "  git -C \"$dir\" checkout --quiet --force --detach FETCH_HEAD".into(),
        "  have=$(git -C \"$dir\" rev-parse HEAD)".into(),
        "  [ \"$want\" = main ] || [ \"$have\" = \"$want\" ] || { echo \"sibling $repo is $have, not the pinned $want\" >&2; exit 2; }".into(),
        "  echo \"sibling $repo at $have\"".into(),
        "  siblings_revisions=\"$siblings_revisions$name=$have,\"".into(),
        "}".into(),
    ];
    for (repository, revision) in siblings {
        let (qualified, name) = match repository.split_once('/') {
            Some((_, name)) => (repository.clone(), name),
            None => (
                format!("${{{{ github.repository_owner }}}}/{repository}"),
                repository.as_str(),
            ),
        };
        lines.push(format!(
            "stage_sibling '{name}' \"{qualified}\" '{revision}'"
        ));
    }
    lines.push("export CCID_SIBLINGS_DIR=\"$siblings_dir\" CCID_SIBLINGS_REVISIONS=\"${siblings_revisions%,}\"".into());
    let mut out = lines.join(indent);
    out.push_str(indent);
    out
}

/// Render one Forgejo Actions workflow for the jobs that share a workflow name.
///
/// The workflow carries no operator facts: the runner provides the tool root
/// (`CCID_TOOL_ROOT`, laid out `<root>/ccid/<revision>/<triple>/ccid`) and every
/// cache endpoint through its own environment. A missing tool fails the job; a
/// check never installs a tool and never skips.
fn forgejo_workflow(
    templates: &Templates,
    tool_revision: &str,
    tool_sha256: Option<&str>,
    workflow: &str,
    plans: &[&jobs::Plan],
) -> String {
    let mut branches: Vec<&str> = plans
        .iter()
        .flat_map(|plan| plan.push_branches.iter().map(String::as_str))
        .collect();
    branches.sort_unstable();
    branches.dedup();
    if branches.is_empty() {
        branches.push("main");
    }
    // Jobs of one workflow share its triggers (checked by the caller), so the first job speaks for all.
    let events = &plans[0].events;
    let wants = |event: &str| events.is_empty() || events.iter().any(|e| e == event);
    let mut out = String::from(CROW_MARKER);
    out.push_str("# Forgejo Actions adapter: runs of the declared checks.\n");
    out.push_str("# A newer run of the same ref cancels the older one.\n");
    out.push_str(&format!("name: {workflow}\non:\n"));
    if wants("push") {
        out.push_str(&format!(
            "  push:\n    branches: [{}]\n",
            branches.join(", ")
        ));
        if plans.iter().all(|plan| !plan.paths.is_empty()) {
            let mut paths: Vec<&str> = plans
                .iter()
                .flat_map(|plan| plan.paths.iter().map(String::as_str))
                .collect();
            paths.sort_unstable();
            paths.dedup();
            out.push_str("    paths:\n");
            for path in paths {
                out.push_str(&format!("      - \"{path}\"\n"));
            }
        }
    }
    if wants("pull_request") {
        out.push_str("  pull_request:\n");
    }
    if wants("manual") {
        out.push_str("  workflow_dispatch:\n");
    }
    out.push_str(&format!(
        "concurrency:\n  group: ccid-{workflow}-${{{{ github.ref }}}}\n  cancel-in-progress: true\n"
    ));
    // No CARGO_PROFILE_* or CARGO_TERM_COLOR in the workflow environment: a CARGO_* variable is hashed into every
    // compile-cache key, so the shared build profile arrives as cargo config instead - profiles/dev.toml through `cargo
    // --config` for cargo checks, and the CARGO_HOME config include for commands checks (which get no --config).
    let central = tool_revision.is_empty();
    if !central {
        // A pinned render (schema 1) has no job-run, so its workflow environment carries the fleet's value itself:
        // incremental compilation stays on, CI included. Under CI=true Cargo builds workspace members non-incrementally, which
        // changes their -C metadata, so only CARGO_INCREMENTAL=1 gives a CI build of a PATH crate the key a lane computes.
        // Schema 2 gets the same value from job-run (cache::incremental_default). A repository picks this up with its next render.
        out.push_str("env:\n  CARGO_INCREMENTAL: \"1\"\n");
    }
    out.push_str("jobs:\n");
    let mut previous: Option<&str> = None;
    for plan in plans {
        // The job's declared environment (already validated: no reserved or secret names), shell-quoted, before the checks run.
        let quote_value = |value: &str| format!("'{}'", value.replace('\'', "'\\''"));
        let declared: String = plan
            .environment
            .iter()
            .map(|(key, value)| format!("export {key}={}\n          ", quote_value(value)))
            .collect();
        let declared = format!("{}{declared}", forgejo_siblings_step(&plan.siblings));
        let run = if jobs::is_self_checks_command(&plan.command) {
            // The canonical repository identity comes from the workflow, not from a git remote a runner may have rewritten to a local copy.
            let mut run = String::from(
                "export CI_COMMIT_SHA=\"${{ github.sha }}\" CI_REPOSITORY_URL=\"${{ github.server_url }}/${{ github.repository }}\"\n          exec \"$tool\" check --repo \"$PWD\"",
            );
            for check in &plan.checks {
                run.push_str(&format!(" --check '{check}'"));
            }
            run
        } else {
            // The repository's own script, with the contract the scheduler adapters give it.
            let quote = |word: &str| format!("'{}'", word.replace('\'', "'\\''"));
            let words: Vec<String> = plan.command.iter().map(|word| quote(word)).collect();
            format!(
                "export CCID_BIN=\"$tool\" CI_COMMIT_SHA=\"${{{{ github.sha }}}}\" CI_REPOSITORY_URL=\"${{{{ github.server_url }}}}/${{{{ github.repository }}}}\" CHECKS={}\n          exec {}",
                quote(&plan.checks.join(",")),
                words.join(" ")
            )
        };
        out.push_str(&format!(
            "  {}:\n    runs-on: {}\n",
            plan.job,
            plan.runs_on.as_deref().unwrap_or("light"),
        ));
        // The jobs of one workflow share the repository's target cache, whose lock refuses a second concurrent check: they run one after the other, each regardless of the earlier result.
        if let Some(before) = previous {
            out.push_str(&format!(
                "    needs: [{before}]\n    if: ${{{{ !cancelled() }}}}\n"
            ));
        }
        previous = Some(plan.job.as_str());
        out.push_str("    steps:\n");
        if central {
            out.push_str(
                &templates
                    .forgejo_shim
                    .replace("CCID_JOB", &plan.job)
                    .replace("CCID_CLASS", plan.runs_on.as_deref().unwrap_or("light")),
            );
            if plan.archive_inputs {
                out.push_str(templates.forgejo_archive);
            }
            continue;
        }
        out.push_str(
            &templates
                .forgejo_steps
                .replace("CCID_TOOL_REVISION", tool_revision)
                .replace(
                    "CCID_TOOL_SHA_LINE",
                    &tool_sha256
                        .map(|digest| format!("          CCID_TOOL_SHA256: {digest}\n"))
                        .unwrap_or_default(),
                )
                .replace("CCID_RUN", &format!("{declared}{run}")),
        );
        if plan.archive_inputs {
            out.push_str(templates.forgejo_archive);
        }
    }
    out
}

/// render_schema 2: the stable shim (`forgejo-shim.yml`) finds the centrally chosen ccid and hands over to `ccid job-run`.
/// After the checks passed, `forgejo-archive.yml` sends the locked flake inputs to the target the runner names, so other
/// runners substitute them; a runner without a target says so and moves on.
fn forgejo_workflow_central(
    templates: &Templates,
    workflow: &str,
    plans: &[&jobs::Plan],
) -> String {
    forgejo_workflow(templates, "", None, workflow, plans)
}

/// Single-pass template substitution: tool revision, secret names, then
/// caller pairs. Values are pre-validated (no CCID_, no shell metachars),
/// so substituted text can never reintroduce a placeholder.
fn substitute(template: &str, config: &Config, pairs: &[(&str, &str)]) -> String {
    let mut rendered = template
        .replace("CCID_TOOL_REVISION", &config.tool_revision)
        .replace("CCID_SECRET_BINARY", &config.tool_secret_binary)
        .replace("CCID_SECRET_SHA", &config.tool_secret_binary_sha256);
    for (key, value) in pairs {
        rendered = rendered.replace(key, value);
    }
    rendered
}

fn validate_push_name(name: &str) -> Result<()> {
    if name.is_empty()
        || name.contains("CCID")
        || !name
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || b"_-".contains(&c))
    {
        return Err(failure(
            "Push adapter names must be plain and avoid the CCID_ prefix",
        ));
    }
    Ok(())
}

fn validate_resolver_token_secret(name: &str) -> Result<()> {
    validate_crow_secret(name, "[render].resolver_token_secret")
}

/// A Crow repository secret reference: a name only, never a value.
fn validate_crow_secret(name: &str, field: &str) -> Result<()> {
    let bytes = name.as_bytes();
    if bytes.is_empty() || bytes.len() > 64 {
        return Err(failure(format!("Invalid {field}: must be 1-64 characters")));
    }
    let first_ok = bytes[0].is_ascii_alphanumeric() || bytes[0] == b'_';
    let rest_ok = bytes[1..]
        .iter()
        .all(|b| b.is_ascii_alphanumeric() || *b == b'_' || *b == b'-' || *b == b'.');
    if !first_ok || !rest_ok {
        return Err(failure(format!(
            "Invalid {field}: use [A-Za-z0-9_.-], leading [A-Za-z0-9_]"
        )));
    }
    Ok(())
}

/// Secret variable names are plain uppercase identifiers that cannot shadow
/// anything the scheduler, the reporter or the resolver owns.
fn validate_secret_environment(secrets: &BTreeMap<String, String>) -> Result<()> {
    for (name, secret) in secrets {
        let bytes = name.as_bytes();
        if bytes.is_empty()
            || bytes.len() > 64
            || !bytes[0].is_ascii_uppercase()
            || !bytes
                .iter()
                .all(|b| b.is_ascii_uppercase() || b.is_ascii_digit() || *b == b'_')
            || name.starts_with("CI_")
            || name.starts_with("CCID_")
            || name.starts_with("CFRG_RESOLVER_")
            || jobs::reserved_env_key(name)
        {
            return Err(failure(format!(
                "Invalid [render].secret_environment name: {name}"
            )));
        }
        validate_crow_secret(secret, "[render].secret_environment secret")?;
    }
    Ok(())
}

/// Userinfo (and therefore passwords) only exists in scheme URLs; scp-like
/// `user@host:path` carries a login name but never a password.
fn authority_has_userinfo(url: &str) -> bool {
    let rest = url
        .strip_prefix("https://")
        .or_else(|| url.strip_prefix("ssh://"));
    match rest {
        Some(rest) => rest
            .split('/')
            .next()
            .is_some_and(|authority| authority.contains('@')),
        None => false,
    }
}
/// Shell-safe consumer values: they render inside double-quoted adapter
/// strings, so anything beyond plain names and forge URL punctuation fails.
fn validate_consumer(entry: &PushConsumer) -> Result<PushConsumer> {
    for value in [
        &entry.branch,
        &entry.consumer_branch,
        &entry.job,
        &entry.self_name,
    ] {
        if value.is_empty()
            || value.contains("CCID")
            || !value
                .bytes()
                .all(|c| c.is_ascii_alphanumeric() || b"_-".contains(&c))
        {
            return Err(failure(
                "Push consumer branches, jobs and names must be plain",
            ));
        }
    }
    if entry.consumer.is_empty()
        || entry.consumer.contains("CCID")
        || !entry
            .consumer
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || b"._-:/@".contains(&c))
        || !(entry.consumer.starts_with("https://")
            || entry.consumer.starts_with("ssh://")
            || entry.consumer.starts_with("git@"))
        || authority_has_userinfo(&entry.consumer)
    {
        return Err(failure(
            "Push consumer URL must be a plain forge URL without credentials",
        ));
    }
    Ok(entry.clone())
}
/// Inject the optional resolver token into an already-built Crow adapter.
/// Absent secret returns the input byte-identical (preserving auxiliary
/// source variables). Present secret appends exactly one
/// `CFRG_RESOLVER_FORGEJO_TOKEN: { from_secret: <quoted> }` entry to the
/// repository-job environment; native-status steps are untouched. The secret
/// name is quoted with `serde_json` (valid YAML), never interpreted raw.
/// The jobs that gate landing: the manifest's `[verdict] jobs`, else `verify`
/// when the repository declares such a job, else none (no verdict is posted).
fn gating_jobs(parsed: &crate::Manifest) -> Result<Vec<String>> {
    let jobs: Vec<String> = match &parsed.verdict {
        Some(verdict) => verdict.jobs.clone(),
        None if parsed.jobs.contains_key("verify") => vec!["verify".to_owned()],
        None => vec![],
    };
    for job in &jobs {
        if !parsed.jobs.contains_key(job) {
            return Err(failure(format!("[verdict] names undeclared job: {job}")));
        }
        if !job
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"_.-".contains(&b))
        {
            return Err(failure("[verdict] jobs must be plain job names"));
        }
    }
    let mut unique = jobs.clone();
    unique.sort();
    unique.dedup();
    if unique.len() != jobs.len() {
        return Err(failure("[verdict] jobs must be unique"));
    }
    Ok(jobs)
}

/// Bake the gating jobs into the status steps of a rendered adapter.
fn inject_gating(base: String, gating: &[String]) -> Result<String> {
    if base.matches(GATING_PLACEHOLDER).count() != 3 {
        return Err(failure("Render template lost its verdict placeholders"));
    }
    Ok(base.replace(GATING_PLACEHOLDER, &gating.join(",")))
}

fn inject_resolver_token(
    base: String,
    tool_revision: &str,
    secret: Option<&str>,
) -> Result<String> {
    let Some(secret) = secret else {
        return Ok(base);
    };
    validate_resolver_token_secret(secret)?;
    // serde_json string quoting is valid YAML and escapes control chars.
    let quoted = serde_json::to_string(secret)?;
    let pin_line = format!("      CCID_REVISION: '{tool_revision}'\n");
    if base.matches(&pin_line).count() != 1 {
        return Err(failure("Render template lost its CCID_REVISION pin"));
    }
    let insertion =
        format!("{pin_line}      {RESOLVER_TOKEN_ENV}:\n        from_secret: {quoted}\n");
    Ok(base.replacen(&pin_line, &insertion, 1))
}

/// Project the declared secret environment into an already-built Crow
/// adapter: one `NAME: { from_secret: <quoted> }` entry per declared variable
/// in the repository-job environment, in name order. No declaration returns
/// the input byte-identical.
fn inject_secret_environment(
    base: String,
    tool_revision: &str,
    secrets: &BTreeMap<String, String>,
) -> Result<String> {
    if secrets.is_empty() {
        return Ok(base);
    }
    let pin_line = format!("      CCID_REVISION: '{tool_revision}'\n");
    if base.matches(&pin_line).count() != 1 {
        return Err(failure("Render template lost its CCID_REVISION pin"));
    }
    let mut insertion = pin_line.clone();
    for (name, secret) in secrets {
        // serde_json string quoting is valid YAML and escapes control chars.
        let quoted = serde_json::to_string(secret)?;
        insertion.push_str(&format!("      {name}:\n        from_secret: {quoted}\n"));
    }
    Ok(base.replacen(&pin_line, &insertion, 1))
}

fn metadata(path: &Path) -> Result<Option<fs::Metadata>> {
    match fs::symlink_metadata(path) {
        Ok(value) => Ok(Some(value)),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(error.into()),
    }
}

fn owned(path: &Path, content: &str) -> bool {
    if path == Path::new(INVENTORY) {
        serde_json::from_str::<serde_json::Value>(content)
            .ok()
            .and_then(|value| value.get("generator").cloned())
            .is_some_and(|value| value.as_str() == Some(GENERATOR))
    } else if path == Path::new(upstream_sync::WORKFLOW) {
        content.starts_with(upstream_sync::MARKER)
    } else {
        content.starts_with(CROW_MARKER)
    }
}

fn obsolete(repo: &Path, outputs: &BTreeMap<PathBuf, String>) -> Result<Vec<PathBuf>> {
    let mut obsolete = Vec::new();
    // A repository that removed [check_shell] loses the generated shell; a
    // foreign .ci/check-shell.nix stays untouched.
    if !outputs.contains_key(Path::new(CHECK_SHELL)) {
        let path = repo.join(CHECK_SHELL);
        if let Some(metadata) = metadata(&path)? {
            if metadata.is_file() && !metadata.file_type().is_symlink() {
                let bytes = fs::read(&path)?;
                if bytes.starts_with(CROW_MARKER.as_bytes()) {
                    obsolete.push(PathBuf::from(CHECK_SHELL));
                }
            }
        }
    }
    for base in [".crow", FORGEJO_DIRECTORY] {
        let directory = repo.join(base);
        if !directory.exists() {
            continue;
        }
        for entry in fs::read_dir(directory)? {
            let entry = entry?;
            let relative = Path::new(base).join(entry.file_name());
            if outputs.contains_key(&relative)
                || !matches!(
                    relative.extension().and_then(|v| v.to_str()),
                    Some("yaml" | "yml")
                )
            {
                continue;
            }
            // Never follow or delete an unrelated symlink or directory.
            if entry.file_type()?.is_file() {
                let bytes = fs::read(entry.path())?;
                if bytes.starts_with(CROW_MARKER.as_bytes())
                    || bytes.starts_with(upstream_sync::MARKER.as_bytes())
                {
                    obsolete.push(relative);
                }
            }
        }
    }
    obsolete.sort();
    Ok(obsolete)
}

