//! Enter a rendered check-shell before a build or check runs.
//!
//! A repository that opts in gets `.ci/check-shell.nix` from `ccid render`. The
//! file is the one definition of CI's C toolchain and native libraries. `ccid
//! check`, `ccid cached` and the job command of `ccid job-run` therefore run
//! inside exactly that file, the way CI always entered a hand-written
//! check-shell, so a lane that sources the same file builds with the same
//! inputs. The file is generated (its first line is the render marker): a
//! hand-written shell stays owned by the repository and is never entered
//! implicitly.
use crate::{failure, Result};
use std::{
    ffi::OsString,
    path::Path,
    process::{Command, ExitCode},
};

/// First line of a shell rendered by `ccid render`.
pub const MARKER: &str = "# Generated by ccid render v1;";
pub const SHELL: &str = ".ci/check-shell.nix";

/// True when the repository has a renderer-owned check-shell and this process
/// is not already inside a nix shell.
fn needed(repo: &Path) -> bool {
    if std::env::var_os("NIX_BUILD_TOP").is_some() || std::env::var_os("IN_NIX_SHELL").is_some() {
        return false;
    }
    match std::fs::read_to_string(repo.join(SHELL)) {
        Ok(content) => content.starts_with(MARKER),
        Err(_) => false,
    }
}

/// Single-quote one argument for the shell `nix-shell --run` starts.
fn quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

/// The `nix-shell` invocation that runs `argv` (program and arguments) inside
/// the repository's rendered shell.
fn invocation(argv: &[OsString]) -> Result<Vec<String>> {
    let mut words = Vec::with_capacity(argv.len());
    for value in argv {
        let value = value
            .to_str()
            .ok_or_else(|| failure("check-shell command argument is not valid UTF-8"))?;
        words.push(quote(value));
    }
    Ok(vec![
        "nix-shell".into(),
        SHELL.into(),
        "--run".into(),
        format!("exec {}", words.join(" ")),
    ])
}

/// Re-exec this ccid inside the repository's rendered shell. Returns without
/// doing anything when the repository has no generated shell or this process
/// already runs inside one.
pub fn enter(repo: &Path) -> Result<()> {
    if !needed(repo) {
        return Ok(());
    }
    let exe = std::env::current_exe()?;
    let mut argv = vec![exe.into_os_string()];
    argv.extend(std::env::args_os().skip(1));
    let words = invocation(&argv)?;
    // A re-exec replaces this process: the shell owns the build, its exit code
    // is the command's. `--run` already reports startup failures as non-zero.
    let status = Command::new(&words[0])
        .args(&words[1..])
        .current_dir(repo)
        .status()
        .map_err(|error| failure(format!("cannot enter {SHELL}: {error}")))?;
    std::process::exit(status.code().unwrap_or(2));
}

/// Run one argv inside the repository's rendered shell, for a caller that is
/// already past its own setup (the job command of `ccid job-run`). `None` when
/// no generated shell applies.
pub fn command(repo: &Path, argv: &[OsString]) -> Result<Option<Command>> {
    if !needed(repo) {
        return Ok(None);
    }
    let words = invocation(argv)?;
    let mut command = Command::new(&words[0]);
    command.args(&words[1..]).current_dir(repo);
    Ok(Some(command))
}

/// Outcome type used by `enter`'s callers in tests.
pub fn exit_code(status: std::process::ExitStatus) -> ExitCode {
    ExitCode::from(status.code().unwrap_or(2) as u8)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quotes_one_argument_without_leaving_the_quoting() {
        assert_eq!(quote("plain"), "'plain'");
        assert_eq!(quote("it's"), "'it'\\''s'");
        assert_eq!(quote("a b"), "'a b'");
    }

    #[test]
    fn only_a_renderer_owned_shell_is_entered() {
        let root = tempfile::tempdir().unwrap();
        std::fs::create_dir_all(root.path().join(".ci")).unwrap();
        assert!(!needed(root.path()), "absent shell is not entered");
        std::fs::write(root.path().join(SHELL), "# handwritten\n").unwrap();
        assert!(
            !needed(root.path()),
            "a foreign shell stays owned by the repo"
        );
        std::fs::write(
            root.path().join(SHELL),
            format!("{MARKER} edit .ci/ccid.toml instead.\n"),
        )
        .unwrap();
        assert!(needed(root.path()));
        assert!(command(root.path(), &[OsString::from("true")])
            .unwrap()
            .is_some());
    }

    #[test]
    fn invokes_nix_shell_on_the_rendered_file() {
        let argv = vec![OsString::from("ccid"), OsString::from("check")];
        assert_eq!(
            invocation(&argv).unwrap(),
            vec!["nix-shell", SHELL, "--run", "exec 'ccid' 'check'"]
        );
    }
}
