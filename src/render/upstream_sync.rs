//! The upstream sync: the workflow that keeps a downstream repository on its upstream (`docs/upstream-sync.md`).
//!
//! Rendered into every repository that declares an upstream in `ccvl-downstream.json`:
//! `.forgejo/workflows/upstream-sync.yml`, dispatched only (nothing polls). The declaration is the repository's own
//! file; nothing is declared twice and no manifest key is added.

use super::{metadata, Templates};
use crate::{failure, jobs, Result};
use std::{
    collections::BTreeMap,
    path::{Path, PathBuf},
};

pub(super) const WORKFLOW: &str = ".forgejo/workflows/upstream-sync.yml";
pub(super) const DECLARATION: &str = "ccvl-downstream.json";
/// The first line of the generated workflow. It differs from the marker of the job adapters on purpose: a ccid that does not
/// know this file does not take it for an obsolete job adapter.
pub(super) const MARKER: &str =
    "# Generated by ccid render v1; edit ccvl-downstream.json instead.\n";
/// The job whose checks gate the merge.
pub(super) const CHECK_JOB: &str = "downstream-check";

/// Files this release introduced: `render --check` accepts their absence (a declared transition), `render` writes them.
const INTRODUCED: &[&str] = &[WORKFLOW];

pub(super) fn introduced(relative: &Path) -> bool {
    INTRODUCED.iter().any(|path| Path::new(path) == relative)
}

#[derive(Debug, PartialEq, Eq)]
struct Declaration {
    url: String,
    branch: String,
}

/// `https://host/owner/repo.git` with nothing a shell or YAML would take for syntax.
fn valid_url(url: &str) -> bool {
    let Some(rest) = url.strip_prefix("https://") else {
        return false;
    };
    let Some(path) = rest.strip_suffix(".git") else {
        return false;
    };
    let parts: Vec<&str> = path.split('/').collect();
    parts.len() == 3
        && parts.iter().all(|part| {
            !part.is_empty()
                && *part != "."
                && *part != ".."
                && part
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b"._-:".contains(&b))
        })
        && !parts[0].starts_with(['.', '-'])
}

fn valid_branch(branch: &str) -> bool {
    !branch.is_empty()
        && branch.len() <= 100
        && !branch.starts_with(['-', '/', '.'])
        && !branch.contains("..")
        && !branch.ends_with(['/', '.'])
        && branch
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"._-/".contains(&b))
}

fn read(repo: &Path) -> Result<Option<Declaration>> {
    let path = repo.join(DECLARATION);
    match metadata(&path)? {
        None => return Ok(None),
        Some(found) if !found.is_file() || found.file_type().is_symlink() => {
            return Err(failure(format!("{DECLARATION} is not a regular file")))
        }
        Some(_) => {}
    }
    let value: serde_json::Value = serde_json::from_slice(&std::fs::read(&path)?)
        .map_err(|error| failure(format!("{DECLARATION} is not valid JSON: {error}")))?;
    if value.get("schema_version").and_then(|v| v.as_u64()) != Some(1) {
        return Err(failure(format!("{DECLARATION}: schema_version 1 required")));
    }
    let upstream = value
        .get("upstream")
        .ok_or_else(|| failure(format!("{DECLARATION}: upstream is missing")))?;
    let url = upstream
        .get("url")
        .and_then(|v| v.as_str())
        .ok_or_else(|| {
            failure(format!(
                "{DECLARATION}: upstream.url is required to sync (an https://host/owner/repo.git clone URL)"
            ))
        })?;
    if !valid_url(url) {
        return Err(failure(format!(
            "{DECLARATION}: upstream.url must be https://host/owner/repo.git"
        )));
    }
    let branch = upstream
        .get("branch")
        .and_then(|v| v.as_str())
        .unwrap_or("main");
    if !valid_branch(branch) {
        return Err(failure(format!("{DECLARATION}: invalid upstream.branch")));
    }
    Ok(Some(Declaration {
        url: url.to_owned(),
        branch: branch.to_owned(),
    }))
}

/// `template` with the line that holds only `marker` replaced by `body`, indented to match.
fn splice(template: &str, marker: &str, body: &str) -> Result<String> {
    let mut out = String::new();
    let mut found = false;
    for line in template.split_inclusive('\n') {
        if line.trim() == marker {
            let indent = &line[..line.len() - line.trim_start().len()];
            for text in body.lines() {
                if !text.is_empty() {
                    out.push_str(indent);
                    out.push_str(text);
                }
                out.push('\n');
            }
            found = true;
        } else {
            out.push_str(line);
        }
    }
    if found {
        Ok(out)
    } else {
        Err(failure(format!(
            "The upstream sync template has no {marker} line"
        )))
    }
}

/// The check step: the shim that finds the centrally chosen ccid, handing over to `job-run` on the local merge.
fn check_step(templates: &Templates, job: &str, class: &str) -> Result<String> {
    let shim = templates
        .forgejo_shim
        .replace("CCID_JOB", job)
        .replace("CCID_CLASS", class);
    let mut out = String::new();
    let mut handed_over = false;
    for line in shim.split_inclusive('\n') {
        if line.trim_start().starts_with("exec \"$tool\" job-run") {
            let indent = &line[..line.len() - line.trim_start().len()];
            out.push_str(&format!(
                "{indent}exec \"$tool\" job-run --job '{job}' --repository '${{{{ github.repository }}}}' --sha \"$SYNC_MERGE\" --server-url '${{{{ github.server_url }}}}' --owner '${{{{ github.repository_owner }}}}' --local --source \"$SYNC_WORK\"\n"
            ));
            handed_over = true;
        } else {
            out.push_str(line);
        }
    }
    if !handed_over {
        return Err(failure("The shim template has no job-run hand-over line"));
    }
    // Only a merge that changed the branch is checked; the shim step carries the condition.
    let gated = out.replacen(
        "        env:\n",
        "        if: ${{ env.SYNC_CHECK == '1' }}\n        env:\n",
        1,
    );
    if gated == out {
        return Err(failure("The shim template has no env block to gate"));
    }
    Ok(gated)
}

/// The sync workflow of a repository that declares an upstream; none otherwise.
pub(super) fn outputs(
    repo: &Path,
    jobs: &BTreeMap<String, jobs::Plan>,
    templates: &Templates,
) -> Result<BTreeMap<PathBuf, String>> {
    let Some(declaration) = read(repo)? else {
        return Ok(BTreeMap::new());
    };
    let plan = jobs
        .get(CHECK_JOB)
        .filter(|plan| plan.scheduler == jobs::Scheduler::Forgejo);
    let plan = plan.ok_or_else(|| {
        failure(format!(
            "{DECLARATION} declares an upstream, so the manifest needs a Forgejo job named {CHECK_JOB} that checks the merge"
        ))
    })?;
    let class = plan.runs_on.as_deref().unwrap_or("light");
    let step = check_step(templates, CHECK_JOB, class)?;
    let workflow = templates
        .upstream_sync
        .replacen(
            "# Generated by ccid render v1; edit .ci/ccid.toml instead.\n",
            MARKER,
            1,
        )
        .replace("CCID_CLASS", class)
        .replace("CCID_SYNC_URL", &declaration.url)
        .replace("CCID_SYNC_UPSTREAM_BRANCH", &declaration.branch);
    let workflow = splice(&workflow, "CCID_SYNC_CHECK", step.trim_end_matches('\n'))?;
    let workflow = splice(&workflow, "CCID_SYNC_MERGE", templates.upstream_sync_merge)?;
    let workflow = splice(
        &workflow,
        "CCID_SYNC_PUBLISH",
        templates.upstream_sync_publish,
    )?;
    if !workflow.starts_with(MARKER) {
        return Err(failure("The upstream sync template lost its marker"));
    }
    Ok(BTreeMap::from([(PathBuf::from(WORKFLOW), workflow)]))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn urls_are_clone_urls_and_nothing_else() {
        assert!(valid_url("https://git.example/org/repo.git"));
        assert!(valid_url("https://git.example:3000/org/re.po-1.git"));
        for url in [
            "",
            "http://git.example/org/repo.git",
            "https://git.example/org/repo",
            "https://git.example/repo.git",
            "https://git.example/a/b/repo.git",
            "https://git.example/org/re'po.git",
            "https://git.example/org/$(id).git",
            "https://git.example/../repo.git",
            "https://git.example/org/re po.git",
            "https://-host/org/repo.git",
        ] {
            assert!(!valid_url(url), "{url}");
        }
    }

    #[test]
    fn branches_are_plain_names() {
        for branch in ["main", "release/1.0", "a-b_c.d"] {
            assert!(valid_branch(branch), "{branch}");
        }
        for branch in ["", "-x", "/x", "a..b", "a b", "a'b", "a$b", "x/", "x."] {
            assert!(!valid_branch(branch), "{branch}");
        }
    }
}
